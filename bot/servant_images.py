# شناسههای فایل برای سازگاری با نسخههای قبلی.
SERVANT_IMAGES = {i: SERVANT_IMAGE_DIR / f"{SERVANT_IMAGE_BY_ID.get(i, i):02d}.jpg" for i in range(1, 37)}


def get_servant_image_by_id(base_id: int):
    try:
        return SERVANT_IMAGES.get(int(base_id))
    except (TypeError, ValueError):
        return None


def get_servant_image(servant_key):
    try:
        return get_servant_image_by_id(int(servant_key))
    except (TypeError, ValueError):
        return None
