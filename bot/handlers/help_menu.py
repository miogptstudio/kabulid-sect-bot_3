@router.callback_query(F.data.startswith("helpsec:"))
async def cb_help_section(callback: CallbackQuery):
    parts = callback.data.split(":")
    if len(parts) < 3:
        await callback.answer()
        return
    try:
        owner = int(parts[1])
    except ValueError:
        owner = 0
    if owner and callback.from_user.id != owner:
        await callback.answer("این منو برای تو نیست.", show_alert=True)
        return
    key = parts[2]
    if key == "all":
        chunks = [f"📋 <b>همه دستورات بازی</b> — v{BOT_VERSION}\n\n"
                  "این فهرست کاربرد هر دستور را هم می‌گوید تا اشتباهی اجرا نشود.\n"]
        for _, (title, items) in SECTIONS.items():
            chunks.append(f"\n<b>{title}</b>\n{_render_section(title, items)}\n")
        text = "\n".join(chunks)
        await callback.message.edit_caption(
            caption=f"📋 <b>همه دستورات</b> — v{BOT_VERSION}\n\nفهرست کامل در پیام‌های بعدی ارسال می‌شود.",
            reply_markup=_kb(owner),
        )
        for i in range(0, len(text), 3900):
            await callback.message.answer(text[i:i + 3900])
        await callback.answer()
        return
    if key not in SECTIONS:
        await callback.answer("بخش نامعتبر است.", show_alert=True)
        return
    title, items = SECTIONS[key]
    text = f"<b>{title}</b>\n\n{_render_section(title, items)}"
    await callback.message.edit_caption(
        caption=f"<b>{title}</b>\n\nجزئیات کامل در پیام بعدی 👇",
        reply_markup=_kb(owner),
    )
    for i in range(0, len(text), 3900):
        await callback.message.answer(text[i:i + 3900])
    await callback.answer()


