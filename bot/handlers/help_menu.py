@router.callback_query(F.data.startswith("helpsec:"))
async def cb_help_section(callback: CallbackQuery):
    parts = callback.data.split(":")
    if len(parts) < 3:
        await callback.answer()
        return
    try:
        owner = int(parts[1])
    except ValueError:
        owner = 0
    if owner and callback.from_user.id != owner:
        await callback.answer("این منو برای تو نیست.", show_alert=True)
        return
    key = parts[2]
    if key == "all":
        chunks = [f"📋 <b>همه دستورات</b> — v{BOT_VERSION}\n"]
        for _, (title, items) in SECTIONS.items():
            section = _render_limited(items, 500)
            if section:
                chunks.append(f"\n<b>{escape(title)}</b>\n{section}")
        text = "\n".join(chunks)
        if len(text) <= 3900:
            try:
                await callback.message.edit_caption(caption=text, reply_markup=_kb(owner))
            except Exception:
                try:
                    await callback.message.edit_text(text, reply_markup=_kb(owner))
                except Exception:
                    await callback.message.answer(text, reply_markup=_kb(owner))
        else:
            # تلگرام سقف 4096 دارد؛ همه دستورات را در چند پیام سالم میفرستیم.
            await callback.message.answer(f"📋 <b>همه دستورات</b> — v{BOT_VERSION}")
            buf = ""
            for _, (title, items) in SECTIONS.items():
                block = f"<b>{escape(title)}</b>\n{_render_limited(items, 900)}\n\n"
                if len(buf) + len(block) > 3900 and buf:
                    await callback.message.answer(buf)
                    buf = ""
                buf += block
            if buf:
                await callback.message.answer(buf, reply_markup=_kb(owner))
        await callback.answer()
        return
    if key not in SECTIONS:
        await callback.answer("بخش نامعتبر است.", show_alert=True)
        return
    title, items = SECTIONS[key]
    section = _render_limited(items, 900)
    text = f"<b>{escape(title)}</b>\n\n{section}\n\n📌 برای فهرست کامل: /commands"
    try:
        await callback.message.edit_caption(caption=text, reply_markup=_kb(owner))
    except Exception:
        try:
            await callback.message.edit_text(text, reply_markup=_kb(owner))
        except Exception:
            await callback.message.answer(text, reply_markup=_kb(owner))
    await callback.answer()


